/**
 * Copies the built pages to ../web/ so the shared preview links keep resolving
 * to the same URLs they always have.
 *
 * The mapping looks inverted, and it is — deliberately. Those two preview links
 * were published before the Astro project existed, from these exact file paths.
 * Changing a path would mint a new link and orphan whatever has been shared.
 *
 *   dist/index.html              (Northwest Ag Technologies)  ->  ../web/nwagtech/index.html
 *   dist/verde-house/index.html  (Verde House)                ->  ../web/index.html
 *
 * Edit src/. Never edit ../web/ — `npm run build` overwrites it.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dist = resolve(here, '../dist');
const web = resolve(here, '../../web');

const routes = [
  { from: `${dist}/index.html`, to: `${web}/nwagtech/index.html`, name: 'Northwest Ag Technologies' },
  { from: `${dist}/verde-house/index.html`, to: `${web}/index.html`, name: 'Verde House' },
  { from: `${dist}/soil-sampling/index.html`, to: `${web}/soil-sampling/index.html`, name: 'Contract Soil Sampling' },
];

for (const { from, to, name } of routes) {
  const html = await readFile(from, 'utf8');
  const banner = `<!-- ${name} — generated by \`npm run build\` in site/. Do not edit; edit site/src. -->\n`;
  await mkdir(dirname(to), { recursive: true });
  await writeFile(to, banner + html);
  console.log(`  ${name.padEnd(28)} ${(html.length / 1024).toFixed(0)} KB  ->  web/${to.slice(web.length + 1)}`);
}
